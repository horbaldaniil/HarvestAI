import { api } from "./client";

export interface ShapBar {
  name: string;
  value: number | null;
  contribution: number;
}

export interface PredictionRead {
  id: number;
  field_id: number;
  model_name: string;
  model_version: string;
  value_tha: number;
  confidence: number | null;
  /**
   * XGBoost-only 90 % prediction interval (5th–95th percentile via
   * quantile regression). Stack / RF / LGBM don't store quantile
   * siblings — `null` in those cases, UI renders the point
   * estimate alone.
   */
  value_tha_q05: number | null;
  value_tha_q95: number | null;
  /**
   * Family that produced the SHAP contributions. Equals the headline
   * model family when it's a tree (xgboost / rf / lgbm); differs when
   * the resolved model is `stack` and we fell back to a
   * sibling tree for interpretability. UI shows a small disclaimer
   * when these don't match.
   */
  explainer_source: string | null;
  shap_top_json: ShapBar[];
  /**
   * 2–3 sentence Ukrainian narrative generated by gpt-4o-mini in the
   * predict-yield worker. Cached on the row — page-views never hit
   * OpenAI. `null` when LLM wasn't configured or the call failed.
   */
  summary_text: string | null;
  predicted_at: string;
}

export interface JobHandle {
  job_id: string;
  queue: string;
  status_url: string;
}

export async function getLatestPrediction(
  fieldId: number,
): Promise<PredictionRead | null> {
  const { data } = await api.get<PredictionRead | null>(
    `/api/fields/${fieldId}/predictions/latest`,
  );
  return data;
}

export async function recomputePrediction(
  fieldId: number,
): Promise<JobHandle> {
  const { data } = await api.post<JobHandle>(
    `/api/fields/${fieldId}/predictions/recompute`,
  );
  return data;
}

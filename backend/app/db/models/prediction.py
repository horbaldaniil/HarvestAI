"""Yield prediction ORM model.

One row per (field, model_version, predicted_at). Multiple predictions can
exist for a field over time as the season progresses and observations
accumulate. The latest one wins in the UI, but history is preserved so a
user can see how the forecast evolved.
"""
from __future__ import annotations

from datetime import datetime

from sqlalchemy import BigInteger, DateTime, ForeignKey, Numeric, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampMixin


class Prediction(Base, TimestampMixin):
    __tablename__ = "predictions"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    field_id: Mapped[int] = mapped_column(
        BigInteger,
        ForeignKey("fields.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    model_name: Mapped[str] = mapped_column(String(64), nullable=False)
    model_version: Mapped[str] = mapped_column(String(32), nullable=False)
    # Point estimate (t/ha) + ±confidence (one standard deviation).
    value_tha: Mapped[float] = mapped_column(Numeric(6, 3), nullable=False)
    confidence: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    # XGBoost quantile band (5th / 95th percentile via quantile regression).
    # Populated only when the resolved model is an XGBoost-triple payload;
    # stack / RF / LGBM / CatBoost don't carry quantile siblings, so these
    # stay NULL and the UI renders the point estimate alone.
    value_tha_q05: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    value_tha_q95: Mapped[float | None] = mapped_column(Numeric(6, 3), nullable=True)
    # Which family generated the SHAP contributions. Differs from the
    # `model_name` family when the resolved model is non-tree-explainable
    # (typically `stack`) and we fell back to a sibling tree model for
    # interpretability. NULL if no explainer was available.
    explainer_source: Mapped[str | None] = mapped_column(String(32), nullable=True)
    # JSON for inspection + reproducibility (good for the thesis report).
    features_json: Mapped[dict] = mapped_column(JSONB, nullable=False)
    # Top-N SHAP contributions [{name, value, contribution}, ...]
    shap_top_json: Mapped[list] = mapped_column(JSONB, nullable=False)
    # 2-3 sentence Ukrainian narrative generated by gpt-4o-mini in the
    # predict-yield worker. NULL when OPENAI_API_KEY is not configured
    # or the LLM call failed — UI hides the summary block in that case.
    summary_text: Mapped[str | None] = mapped_column(Text(), nullable=True)
    predicted_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
